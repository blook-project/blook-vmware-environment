# Publish the release package to the org xmake package registry.
#
#   pwsh scripts/publish-registry.ps1 -Package blook-vmware-environment -Version 0.1.0 [-DryRun]
#
# First time (package not in the registry yet) add the manifest from this repo:
#   pwsh scripts/publish-registry.ps1 -Package blook-vmware-environment -Version 0.1.0 `
#        -ManifestFile .\xmake-package\xmake.lua
#
# Requires an authenticated `gh` (repo + workflow scopes).
param(
    [Parameter(Mandatory = $true)][string]$Package,
    [Parameter(Mandatory = $true)][string]$Version,
    [string]$RegistryRepo = 'blook-project/blook-xmake-repo',
    [string]$ManifestFile,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$work = Join-Path $env:TEMP ("bvmenv-registry-" + [guid]::NewGuid().ToString('N'))

function Invoke-Gh([string[]]$Arguments) {
    $out = & gh @Arguments 2>&1
    if ($LASTEXITCODE -ne 0) { throw "gh $($Arguments -join ' ') failed: $out" }
    return $out
}

Write-Host "==> cloning $RegistryRepo"
& gh repo clone $RegistryRepo $work -- --depth 1 | Out-Null
if ($LASTEXITCODE -ne 0) { throw "failed to clone $RegistryRepo" }

# Registry layout: packages/<first-letter>/<package>/xmake.lua + versions/<ver>.lua
$letter = $Package.Substring(0, 1).ToLower()
$pkgDir = Join-Path $work "packages/$letter/$Package"
$verDir = Join-Path $pkgDir "versions"
New-Item -ItemType Directory -Force -Path $verDir | Out-Null

if ($ManifestFile) {
    $manifest = Get-Content $ManifestFile -Raw
} elseif (Test-Path (Join-Path $pkgDir 'xmake.lua')) {
    $manifest = Get-Content (Join-Path $pkgDir 'xmake.lua') -Raw
} else {
    throw "no manifest: pass -ManifestFile $(Join-Path $repoRoot 'xmake-package/xmake.lua')"
}

# Resolve the asset hash from the published release.
Write-Host "==> resolving release asset sha256"
$releaseJson = Invoke-Gh @('release', 'view', "v$Version", '--repo', 'blook-project/blook-vmware-environment', '--json', 'assets')
$assets = ($releaseJson -join "`n") | ConvertFrom-Json
$zipName = "blook-vmware-environment-$Version-windows-x64.zip"
$asset = $assets.assets | Where-Object { $_.name -eq $zipName } | Select-Object -First 1
if (-not $asset) { throw "release v$Version has no asset $zipName" }

$sha = $null
$shaAsset = $assets.assets | Where-Object { $_.name -eq "$zipName.sha256" } | Select-Object -First 1
if ($shaAsset) {
    $tmp = Join-Path $env:TEMP $shaAsset.name
    Invoke-Gh @('release', 'download', "v$Version", '--repo', 'blook-project/blook-vmware-environment', '--pattern', $shaAsset.name, '--output', $tmp, '--clobber') | Out-Null
    $sha = ((Get-Content $tmp -Raw) -split '\s+')[0].ToLower()
}
if (-not $sha) {
    # Fall back: compute from the downloaded zip.
    $tmp = Join-Path $env:TEMP $zipName
    Invoke-Gh @('release', 'download', "v$Version", '--repo', 'blook-project/blook-vmware-environment', '--pattern', $zipName, '--output', $tmp, '--clobber') | Out-Null
    $sha = (Get-FileHash $tmp -Algorithm SHA256).Hash.ToLower()
}
Write-Host "==> sha256 $sha"

$manifest = $manifest -replace '<sha256-placeholder-updated-by-publish-registry>', $sha
$manifest = $manifest -replace 'add_versions\("0\.1\.0",\s*"[^"]*"\)', "add_versions(`"$Version`", `"$sha`")"
Remove-Item (Join-Path $pkgDir 'xmake.lua') -ErrorAction SilentlyContinue
Set-Content -LiteralPath (Join-Path $pkgDir 'xmake.lua') -Value $manifest -Encoding UTF8

$versionFile = Join-Path $verDir "$Version.lua"
Set-Content -LiteralPath $versionFile -Encoding UTF8 -Value @"
-- package version manifest generated by publish-registry.ps1
package("$Package")
    add_versions("$Version", "$sha")
package_end()
"@

Write-Host "==> files prepared:"
Get-ChildItem -Recurse $pkgDir | ForEach-Object { Write-Host ("    " + $_.FullName.Substring($work.Length + 1)) }

if ($DryRun) {
    Write-Host '==> -DryRun: not committing'
    Remove-Item -Recurse -Force $work
    exit 0
}

Push-Location $work
try {
    & git config user.name 'MicroBlock'
    & git config user.email '66859419+std-microblock@users.noreply.github.com'
    & git add -A
    if ((& git status --porcelain).Length -eq 0) {
        Write-Host '==> registry already up to date'
        exit 0
    }
    & git commit -m "$Package`: publish $Version" | Out-Null
    & git push | Out-Null
    Write-Host "==> published $Package $Version to $RegistryRepo"
} finally {
    Pop-Location
    Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
}
